//! The **candidate** width-8 Goldilocks Poseidon2 round constants for the next constraint set
//! (monorepo issue 60, ZKVM-107). **Nothing hashes with this table today**: the live constraint
//! set, every verifier key, every program digest and the chain's genesis use
//! [`crate::poseidon2_constants`] (the "RandZK" development draw), and this file changes none of
//! them. It exists so the replacement is chosen, derived, committed and tested before the cut
//! that adopts it; `docs/05-roadmap.md`, "ZKVM-107: the round-constant switch-over", is the
//! checklist for that cut.
//!
//! ## Where the numbers come from
//!
//! They are the output of the Poseidon paper's Grain LFSR for the parameters of this
//! permutation and nothing else — field type 1 (prime), S-box 0 (`x^alpha`, here `x^7`),
//! `n = 64`, `t = 8`, `R_F = 8`, `R_P = 22` — as [`crate::poseidon2_grain`] documents step by
//! step. There is no seed to choose. Three things pin the table, and the tests below check each:
//!
//! - `the_table_is_the_grain_derivation` re-runs [`crate::poseidon2_grain::goldilocks_width_8`]
//!   and compares all 86 values;
//! - `tools/poseidon2_grain/grain.py --check` is a second implementation (standard-library
//!   Python) that does the same without building the crate;
//! - `the_table_is_the_one_plonky3_ships` compares with `p3-goldilocks 0.7.0`'s
//!   `GOLDILOCKS_POSEIDON2_RC_8_{EXTERNAL_INITIAL, INTERNAL, EXTERNAL_FINAL}`, which upstream
//!   documents as "Generated by the Grain LFSR with parameters: field_type=1, alpha=7
//!   (exp_flag=0), n=64, t=8, R_F=8, R_P=22". The two derivations were written independently
//!   and agree, so this table is also the one external cryptanalysis of Plonky3's width-8
//!   Goldilocks Poseidon2 is about.
//!
//! The linear layers are not constants of this file and do not change at the switch: the
//! external layer is the Poseidon2 paper's `M4`-circulant matrix and the internal layer is
//! `p3-goldilocks`'s `MATRIX_DIAG_8_GOLDILOCKS`, exactly as today (`tables::poseidon2::
//! {mds_light, internal_matmul}`), and the round numbers stay `(8, 22)` with `x^7`.
//!
//! Unlike `poseidon2_constants.rs`, this file is not compiled into `rand-zkvm-cuda` by
//! `#[path]`; the switch-over checklist says what that crate needs.
