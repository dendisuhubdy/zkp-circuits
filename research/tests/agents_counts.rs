//! ZKVM-120: `AGENTS.md`'s counts are generated from the code, and this test fails when they drift.
//!
//! `AGENTS.md` carries one block between `<!-- counts:begin` and `<!-- counts:end -->`: the tables
//! in a batch, the buses, the cpu width, the public-value count, the constraint set and the number
//! of `#[test]` functions. The block is this file's output. When the code moves, regenerate it:
//!
//!     UPDATE_AGENTS_COUNTS=1 cargo test --test agents_counts
//!
//! and commit `AGENTS.md`. Prose elsewhere in the docs should point at the block rather than
//! repeat a number.
use rand_zkvm::machine::{chips, chips_with_modq, Tier, CONSTRAINT_SET};
use rand_zkvm::tables::{blind, cpu};
use std::path::{Path, PathBuf};

const BEGIN: &str = "<!-- counts:begin";
const END: &str = "<!-- counts:end -->";
/// `chips_with_modq`'s order with every optional table present.
const NAMES: [&str; 12] = ["program", "cpu", "memory", "alu", "range", "nibble", "poseidon2", "input", "keccak", "sha256", "modq", "public"];
const OPTIONAL: [&str; 3] = ["keccak", "sha256", "modq"];

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let mut entries: Vec<_> = std::fs::read_dir(dir).unwrap().flatten().map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            rust_files(&p, out);
        } else if p.extension().is_some_and(|e| e == "rs") {
            out.push(p);
        }
    }
}

/// The names declared in `tables::bus`, read from the source: a bus is a `pub const` of type
/// `LookupBus` or `PermutationCheckBus` there, and nothing in the crate lists them.
fn buses(root: &Path) -> Vec<String> {
    let src = std::fs::read_to_string(root.join("src/tables/mod.rs")).unwrap();
    src.lines()
        .filter_map(|l| {
            let l = l.trim();
            let rest = l.strip_prefix("pub const ")?;
            let (name, ty) = rest.split_once(':')?;
            let ty = ty.trim_start();
            (ty.starts_with("LookupBus<") || ty.starts_with("PermutationCheckBus<")).then(|| name.trim().to_string())
        })
        .collect()
}

/// `#[test]` and `#[ignore…]` attribute lines under `src/` and `tests/` (an attribute on a line of
/// its own, which is how every test in the crate is written).
fn tests(root: &Path) -> (usize, usize) {
    let mut files = Vec::new();
    rust_files(&root.join("src"), &mut files);
    rust_files(&root.join("tests"), &mut files);
    let (mut tests, mut ignored) = (0, 0);
    for f in files {
        for l in std::fs::read_to_string(&f).unwrap().lines() {
            let l = l.trim();
            tests += (l == "#[test]") as usize;
            ignored += (l.starts_with("#[ignore]") || l.starts_with("#[ignore =")) as usize;
        }
    }
    (tests, ignored)
}

fn block(root: &Path) -> String {
    let all = chips_with_modq(Tier(10), 7, 7, 10);
    let mandatory = chips(Tier(10), 0, 0);
    assert_eq!(all.len(), NAMES.len(), "a table was added or removed: update NAMES (and OPTIONAL) here");
    assert_eq!(mandatory.len(), NAMES.len() - OPTIONAL.len(), "the optional tables are no longer exactly {OPTIONAL:?}");
    assert_eq!(all[1].table_width(), cpu::col::WIDTH, "NAMES[1] is not the cpu table");
    let widths: Vec<String> = NAMES.iter().zip(&all).map(|(n, c)| format!("`{n}` {}", c.table_width())).collect();
    let buses = buses(root);
    let (tests, ignored) = tests(root);
    let mandatory_names: Vec<String> = NAMES.iter().filter(|n| !OPTIONAL.contains(n)).map(|n| format!("`{n}`")).collect();
    let optional_names: Vec<String> = OPTIONAL.iter().map(|n| format!("`{n}`")).collect();
    let bus_names: Vec<String> = buses.iter().map(|b| format!("`{b}`")).collect();
    [
        format!("{BEGIN} — generated by `tests/agents_counts.rs`, which fails when this block is stale; `UPDATE_AGENTS_COUNTS=1 cargo test --test agents_counts` rewrites it -->"),
        "| | |".into(),
        "|---|---|".into(),
        format!("| constraint set (`machine::CONSTRAINT_SET`) | {CONSTRAINT_SET} |"),
        format!("| AIR tables in a batch | {} to {}: {} mandatory ({}) and up to {} optional ({}) |", mandatory.len(), all.len(), mandatory.len(), mandatory_names.join(", "), OPTIONAL.len(), optional_names.join(", ")),
        format!("| LogUp buses (`tables::bus`) | {}: {} |", buses.len(), bus_names.join(", ")),
        format!("| table widths (each table's own columns) | {} |", widths.join(", ")),
        format!("| committed width | each of the above plus the {} blind columns (`tables::blind`): cpu {} |", blind::col::WIDTH, cpu::col::WIDTH + blind::col::WIDTH),
        format!("| public values (`tables::cpu::pv::NUM`) | {} |", cpu::pv::NUM),
        format!("| `#[test]` functions under `src/` and `tests/` | {tests}, of which {ignored} carry `#[ignore]` |"),
        END.into(),
    ]
    .join("\n")
}

#[test]
fn agents_md_counts_match_the_code() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let path = root.join("AGENTS.md");
    let text = std::fs::read_to_string(&path).unwrap();
    let start = text.find(BEGIN).expect("AGENTS.md has no `<!-- counts:begin` block");
    let end = start + text[start..].find(END).expect("AGENTS.md's counts block has no `<!-- counts:end -->`") + END.len();
    let want = block(&root);
    if std::env::var_os("UPDATE_AGENTS_COUNTS").is_some() {
        std::fs::write(&path, format!("{}{want}{}", &text[..start], &text[end..])).unwrap();
        return;
    }
    assert_eq!(&text[start..end], want, "AGENTS.md's counts block is stale: run `UPDATE_AGENTS_COUNTS=1 cargo test --test agents_counts` and commit AGENTS.md");
}
