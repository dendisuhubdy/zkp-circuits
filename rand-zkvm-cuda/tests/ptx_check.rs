//! `ptx/check-ptx.sh` against the kernel source and against synthetic PTX files (ZKVM-114).
//! No PTX is committed and none can be built without the cuda-oxide toolchain, so what is
//! tested is the checker: its kernel list is the source's, it accepts a file with every entry,
//! and it refuses a missing entry and a wrong digest.
#![cfg(unix)]
use std::path::{Path, PathBuf};
use std::process::Command;

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// The `#[kernel]` functions of `gpu-kernels/src/main.rs`, in source order.
fn kernels_in_source() -> Vec<String> {
    let src = std::fs::read_to_string(crate_dir().join("../gpu-kernels/src/main.rs")).unwrap();
    let mut out = Vec::new();
    let mut lines = src.lines();
    while let Some(l) = lines.next() {
        if l.trim() == "#[kernel]" {
            let f = lines.next().expect("a function follows #[kernel]").trim();
            let name = f.strip_prefix("pub fn ").expect("a kernel is `pub fn`").split('(').next().unwrap();
            out.push(name.to_string());
        }
    }
    out
}

fn kernels_in_script() -> Vec<String> {
    let script = std::fs::read_to_string(crate_dir().join("ptx/check-ptx.sh")).unwrap();
    let line = script.lines().find(|l| l.starts_with("KERNELS=(")).expect("the KERNELS list");
    line.trim_start_matches("KERNELS=(").trim_end_matches(')').split_whitespace().map(str::to_string).collect()
}

fn fake_ptx(dir: &Path, name: &str, kernels: &[String]) -> PathBuf {
    let mut s = String::from("//\n// Generated by a test, not by a compiler\n//\n.version 8.5\n.target sm_80\n.address_size 64\n\n");
    for k in kernels {
        s += &format!(".visible .entry {k}(\n\t.param .u64 {k}_param_0\n)\n{{\n\tret;\n}}\n\n");
    }
    let p = dir.join(name);
    std::fs::write(&p, s).unwrap();
    p
}

fn check(args: &[&std::ffi::OsStr]) -> (bool, String) {
    let out = Command::new("bash").arg(crate_dir().join("ptx/check-ptx.sh")).args(args).output().expect("bash runs");
    (out.status.success(), String::from_utf8_lossy(&out.stdout).into_owned() + &String::from_utf8_lossy(&out.stderr))
}

#[test]
fn the_checkers_kernel_list_is_the_sources() {
    let src = kernels_in_source();
    assert_eq!(src.len(), 11, "eleven kernels: {src:?}");
    assert_eq!(kernels_in_script(), src);
}

#[test]
fn the_checker_accepts_a_complete_file_and_refuses_a_missing_entry_or_a_wrong_digest() {
    let dir = std::env::temp_dir().join(format!("rand-zkvm-cuda-ptx-check-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let all = kernels_in_source();

    let good = fake_ptx(&dir, "good.ptx", &all);
    let (ok, out) = check(&[good.as_os_str()]);
    assert!(ok, "{out}");
    assert!(out.contains("all 11 kernel entries present") && out.contains("nothing to compare with"), "{out}");
    let digest = out.lines().find_map(|l| l.strip_prefix("sha256: ")).unwrap().split_whitespace().next().unwrap().to_string();
    assert_eq!(digest.len(), 64);

    // The right digest, as hex and as a sibling `.sha256` file; then a wrong one.
    let (ok, out) = check(&[good.as_os_str(), std::ffi::OsStr::new(&digest)]);
    assert!(ok && out.contains("sha256 matches"), "{out}");
    std::fs::write(dir.join("good.ptx.sha256"), format!("{digest}  good.ptx\n")).unwrap();
    let (ok, out) = check(&[good.as_os_str()]);
    assert!(ok && out.contains("sha256 matches"), "{out}");
    let wrong = "0".repeat(64);
    let (ok, out) = check(&[good.as_os_str(), std::ffi::OsStr::new(&wrong)]);
    assert!(!ok && out.contains("sha256 mismatch"), "{out}");

    // Each kernel missing in turn.
    for k in &all {
        let rest: Vec<String> = all.iter().filter(|x| *x != k).cloned().collect();
        let bad = fake_ptx(&dir, "bad.ptx", &rest);
        let (ok, out) = check(&[bad.as_os_str()]);
        assert!(!ok && out.contains(&format!("no .visible .entry for: {k}")), "{k}: {out}");
    }
    // A name that only has the kernel's as a prefix is not the kernel.
    let mut renamed = all.clone();
    renamed[0] = format!("{}_v2", all[0]);
    let bad = fake_ptx(&dir, "renamed.ptx", &renamed);
    assert!(!check(&[bad.as_os_str()]).0);
    let _ = std::fs::remove_dir_all(&dir);
}
